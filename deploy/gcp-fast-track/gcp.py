    def install_edge_cert(self, cert_path, key_path):
        """Replace ONLY the browser-facing ingress certificate with the owner-approved public one and publish 443."""
        import datetime
        from cryptography import x509
        from cryptography.hazmat.primitives import serialization
        need(self.c['mode'] == 'gcp' and (self.state / 'installed').is_file(), 'EDGE_CERT_GCP_INSTALLED_ONLY')
        chain = Path(cert_path).read_bytes(); key_pem = Path(key_path).read_bytes()
        certs = x509.load_pem_x509_certificates(chain)
        leaf = certs[0]
        names = set(leaf.extensions.get_extension_for_class(x509.SubjectAlternativeName).value.get_values_for_type(x509.DNSName))
        need({self.c['portal_host'], self.c['auth_host']} <= names, 'EDGE_CERT_SAN')
        need(leaf.not_valid_after_utc > datetime.datetime.now(datetime.timezone.utc) + datetime.timedelta(days=7), 'EDGE_CERT_EXPIRY')
        need(len(certs) >= 2 and leaf.issuer != x509.load_pem_x509_certificate((self.state / 'ca.crt').read_bytes()).subject, 'EDGE_CERT_PUBLIC_CHAIN')
        key = serialization.load_pem_private_key(key_pem, None)
        need(key.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo) ==
             leaf.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo), 'EDGE_KEY_MISMATCH')
        base.save('ingress', 'server.crt', chain); base.save('ingress', 'server.key', key_pem)
        base.save('.', 'edge-public', leaf.not_valid_after_utc.isoformat())
        self.public = True
        self.compose_cmd, self.env = self._compose()
        self.verify()
        self.compose('run', '--rm', '--no-deps', 'materialize')
        self.compose('up', '-d', '--wait', '--wait-timeout', '120', '--force-recreate', '--no-deps', 'ingress')
        log('PASS public certificate for ' + ', '.join(sorted(names)) + ' valid until ' + leaf.not_valid_after_utc.date().isoformat() + '; ingress publishes 0.0.0.0:443 only')

