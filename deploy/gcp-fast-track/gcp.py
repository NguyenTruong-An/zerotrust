        front = json.loads((self.out / 'frontend-artifact.json').read_text())
        need(front['image'] == self.c['frontend_image'] and front['portal'] == self.c['portal_url'], 'FRONTEND_ARTIFACT')
        need(run('docker', 'image', 'inspect', '--format', '{{.Id}}', front['image']).stdout.strip() == front['id'], 'FRONTEND_IMAGE')
        lock = json.loads((ROOT / 'target/pd-r27/release-lock.json').read_text()) if (ROOT / 'target/pd-r27/release-lock.json').exists() else None
        if lock:
            need(run('docker', 'image', 'inspect', '--format', '{{.Id}}', RISK_V5).stdout.strip() == lock['builds']['risk']['id'], 'V5_MIGRATOR_IMAGE')
        for ref, ident in (ff.EXPECTED['mysql84'], ff.EXPECTED['mysql80']):
            need(run('docker', 'image', 'inspect', '--format', '{{.Id}}', ref).stdout.strip() == ident, 'DATA_IMAGE_' + ref)
        need(run('docker', 'image', 'inspect', '--format', '{{.Id}}', TOOLING, check=False).returncode == 0, 'TOOLING_IMAGE')
        need((self.geoip / 'GeoLite2-City.mmdb').is_file() and (self.geoip / 'GeoLite2-ASN.mmdb').is_file(), 'GEOIP_DATA')
        nets = [ipaddress.ip_network(self.c[k]) for k in ('subnet', 'recovery_subnet', 'edge_subnet')]
        for name in run('docker', 'network', 'ls', '--format', '{{.Name}}').stdout.split():
            if name.startswith(self.project + '_'):
                continue
            info = json.loads(run('docker', 'network', 'inspect', '--format', '{{json .IPAM.Config}}', name).stdout or 'null') or []
            for block in info:
                if block.get('Subnet') and ipaddress.ip_network(block['Subnet'], strict=False).version == 4:
                    need(not any(ipaddress.ip_network(block['Subnet'], strict=False).overlaps(x) for x in nets), 'SUBNET_OVERLAP_' + name)
        model = json.loads(self.compose('--profile', '*', 'config', '--format', 'json').stdout)
        sv = model['services']
        need(all(s['labels']['io.zerotrust.scope'] == self.project for s in sv.values()), 'OWNERSHIP')
        need(all(not s.get('ports') for n, s in sv.items() if n != 'ingress'), 'PRIVATE_SERVICE_PUBLISHED')
        expected = {'frontend': self.c['frontend_image'], 'keycloak': IMAGES['keycloak'], 'keycloak-init': IMAGES['keycloak'],
                    'risk': IMAGES['risk'], 'migrate': IMAGES['risk'], 'backend': IMAGES['backend'], 'gateway': IMAGES['gateway'], 'migrate80': RISK_V5}
        for name, ref in expected.items():
            need(sv[name]['image'] == ref, 'SERVICE_IMAGE_' + name)
        ports = sorted((p['host_ip'], int(p['published']), int(p['target'])) for p in sv['ingress']['ports'])
        allowed = [('127.0.0.1', self.c['loopback_port'], 443)] + ([('0.0.0.0', 443, 443)] if self.public else [])
        need(ports == sorted(allowed), 'INGRESS_PORTS')
        need(model['networks']['core']['internal'] and model['networks']['recovery']['internal'], 'INTERNAL_NETWORKS')
        for name, s in sv.items():
            for m in s.get('volumes', []):
                if m['type'] == 'bind':
                    allowed = (name == 'materialize' and m.get('read_only')) or (name == 'risk' and m['target'] == '/geoip' and m.get('read_only'))
                    need(allowed, 'UNEXPECTED_BIND_' + name)
