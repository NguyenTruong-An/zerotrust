        env.update(ACADEMIC_STATE=str(self.state), AD_BIND_PORT=str(c['loopback_port']), AD_PORTAL_HOST=c['portal_host'],
                   AD_EXTERNAL_PORT='443', AD_INGRESS_IP=c['proxy_ip'], AD_CORE_SUBNET=c['subnet'],
                   AD_FRONTEND_IMAGE=c['frontend_image'], AD_RC_PROJECT=self.project, AD_RC_KC=IMAGES['keycloak'],
                   AD_RC_BACKEND=IMAGES['backend'], AD_RC_RISK=IMAGES['risk'], AD_RC_GATEWAY=IMAGES['gateway'])
