        need(run('docker', 'info', '--format', '{{.OSType}}').stdout.strip() == 'linux', 'LINUX_DOCKER')
        need(not os.environ.get('DOCKER_HOST') and not os.environ.get('DOCKER_CONTEXT'), 'REMOTE_DOCKER_REJECTED')
