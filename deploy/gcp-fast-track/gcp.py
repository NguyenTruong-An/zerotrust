    def compose(self, *args, check=True, data=None, timeout=480):
        p = subprocess.run([*self.compose_cmd, *args], env=self.env, input=data, capture_output=True,
                           encoding='utf-8', errors='replace', timeout=timeout, cwd=ROOT)
        if check and p.returncode:
            import re
            safe = sorted(set(re.findall(r'\b(?:[A-Za-z]+Exception|PKIX|unhealthy|V5_[A-Z0-9_]+|no such [a-z ]+|is not running)\b', p.stdout + p.stderr)))
            raise RuntimeError('Compose ' + ' '.join(args[:2]) + ' failed; ' + str(safe))
        return p

