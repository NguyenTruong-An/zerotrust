def run(*args, data=None, timeout=300, check=True, env=None):
    p = subprocess.run(args, input=data, capture_output=True, encoding='utf-8', errors='replace',
                       timeout=timeout, cwd=ROOT, env=env)
    if check and p.returncode:
        raise RuntimeError(f'{args[0]} {args[1]} failed ({p.returncode}); output withheld')
    return p


