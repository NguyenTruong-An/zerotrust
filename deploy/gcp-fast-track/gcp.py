    def monitor(self, helper, proc):
        handled = set(); deadline = time.monotonic() + 1500
        while proc.poll() is None:
            need(time.monotonic() < deadline, 'ACCEPTANCE_TIMEOUT')
            path = self.results / 'acceptance-control.json'
            if path.exists():
                try:
                    item = json.loads(path.read_text())
                except ValueError:
                    item = None
                if item and item['id'] not in handled:
                    need(item['action'] in ('restart-backend', 'stop-risk', 'start-risk'), 'CONTROL_SCOPE')
                    if item['action'] == 'restart-backend':
                        self.compose('restart', 'backend'); self.ready(helper, 'https://backend:8443/api/admin/users', 401)
                    elif item['action'] == 'stop-risk':
                        self.compose('stop', 'risk')
                    else:
                        self.compose('start', 'risk'); self.ready(helper, 'https://risk:8443/actuator/health', 200)
                    tmp = self.results / 'acceptance-ack.json.tmp'; tmp.write_text(json.dumps({'id': item['id']}))
                    for attempt in range(200):
                        try:
                            tmp.replace(self.results / 'acceptance-ack.json'); break
                        except PermissionError:
                            time.sleep(.05)
                    handled.add(item['id'])
            time.sleep(.2)
        lines = proc.stdout.read().decode(errors='replace').splitlines()
        safe = '\n'.join(s for s in lines if s.startswith(('PASS ', 'FAIL ')))
        (self.results / 'native.log').write_text(safe + '\n'); print(safe, flush=True)
        need(proc.returncode == 0, 'NATIVE_ACCEPTANCE_FAILED')


